/**
 * 마크다운 서식을 제거해 SNS에 그대로 붙여넣을 평문으로 바꾼다.
 * 문단 구조(줄바꿈)는 유지하고 기호만 걷어낸다.
 */
export function stripMarkdown(md: string): string {
  return md
    // 코드펜스 표시만 제거 (안의 코드는 유지)
    .replace(/^```[^\n]*$/gm, '')
    // 헤딩 기호
    .replace(/^#{1,6}\s+/gm, '')
    // 인용 기호
    .replace(/^>\s?/gm, '')
    // 불렛 → 가운뎃점
    .replace(/^\s*[-*+]\s+/gm, '· ')
    // 수평선
    .replace(/^\s*([-*_])\1{2,}\s*$/gm, '')
    // 이미지 → alt 텍스트
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
    // 링크 → "텍스트 (url)"
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '$1 ($2)')
    // 볼드/이탤릭
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/(^|[^*])\*([^*\n]+)\*/g, '$1$2')
    .replace(/__([^_]+)__/g, '$1')
    // 인라인 코드
    .replace(/`([^`]+)`/g, '$1')
    // 3줄 이상 공백 → 2줄
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}
